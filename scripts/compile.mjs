// Compiles contracts/BumperBalls.sol with solc-js (no network needed) into build/BumperBalls.json
import solc from "solc";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = path.dirname(new URL(import.meta.url).pathname) + "/..";
const source = fs.readFileSync(`${root}/contracts/BumperBalls.sol`, "utf8");

const input = {
  language: "Solidity",
  sources: { "BumperBalls.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

function findImports(p) {
  try {
    return { contents: fs.readFileSync(require.resolve(p), "utf8") };
  } catch {
    return { error: `not found: ${p}` };
  }
}

const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors || []).filter((e) => e.severity === "error");
for (const e of out.errors || []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const c = out.contracts["BumperBalls.sol"].BumperBalls;
fs.mkdirSync(`${root}/build`, { recursive: true });
fs.writeFileSync(`${root}/build/BumperBalls.json`, JSON.stringify({ abi: c.abi, bytecode: "0x" + c.evm.bytecode.object }, null, 2));
fs.mkdirSync(`${root}/shared`, { recursive: true });
fs.writeFileSync(`${root}/shared/abi.ts`, `// generated by scripts/compile.mjs\nexport const bumperBallsAbi = ${JSON.stringify(c.abi, null, 2)} as const;\n`);
fs.writeFileSync(`${root}/shared/bytecode.ts`, `// generated by scripts/compile.mjs\nexport const bumperBallsBytecode = "0x${c.evm.bytecode.object}" as const;\n`);
console.log(`compiled BumperBalls: ${c.evm.bytecode.object.length / 2} bytes`);
